CREATE TABLE public.candidates (
    id INTEGER PRIMARY KEY CHECK (id > 0),
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    experience_years INTEGER NOT NULL CHECK (experience_years >= 0),
    availability TEXT NOT NULL CHECK (availability IN ('Immediate', '2 weeks', 'Not looking')),
    traits TEXT[] NOT NULL DEFAULT '{}'::TEXT[] CHECK (array_position(traits, NULL) IS NULL),
    quirk TEXT NOT NULL CHECK (btrim(quirk) <> '')
);

CREATE TABLE public.jobs (
    id INTEGER PRIMARY KEY CHECK (id > 0),
    title TEXT NOT NULL CHECK (btrim(title) <> ''),
    min_experience_years INTEGER NOT NULL CHECK (min_experience_years >= 0),
    culture_keywords TEXT[] NOT NULL DEFAULT '{}'::TEXT[] CHECK (array_position(culture_keywords, NULL) IS NULL),
    tagline TEXT NOT NULL CHECK (btrim(tagline) <> '')
);

CREATE TABLE public.skills (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    name TEXT NOT NULL UNIQUE CHECK (btrim(name) <> '' AND name = lower(btrim(name)))
);

CREATE TABLE public.candidate_skills (
    candidate_id INTEGER NOT NULL REFERENCES public.candidates(id) ON DELETE CASCADE,
    skill_id INTEGER NOT NULL REFERENCES public.skills(id) ON DELETE RESTRICT,
    PRIMARY KEY (candidate_id, skill_id)
);

CREATE TABLE public.job_skills (
    job_id INTEGER NOT NULL REFERENCES public.jobs(id) ON DELETE CASCADE,
    skill_id INTEGER NOT NULL REFERENCES public.skills(id) ON DELETE RESTRICT,
    PRIMARY KEY (job_id, skill_id)
);

-- Primary/unique keys supply all selected indexes. No stored matches table.
-- Nonempty job skills and one-dimensional/nonblank metadata are ingestion checks.
